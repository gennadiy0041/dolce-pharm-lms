# Нарезка фрагментов выпуска Qonaev Media для тизера, только изображение.
# Запуск:  .\cut_clips.ps1 -Source "<путь к выпуску .mp4>" -Work "<рабочая папка>"
# Кадры пишутся в <рабочая папка>\clips\cNN\0001.jpg … (25 кадр/с, 1920×1080).
param(
  [Parameter(Mandatory = $true)][string]$Source,
  [Parameter(Mandatory = $true)][string]$Work
)

# имя, начало в выпуске (секунды), число кадров
$clips = @(
  @('c15',  27.70, 30),  # 0:27,70  завод с воздуха
  @('c00', 531.00, 60),  # 8:51,00  роторный стол сборки шприцев
  @('c16',  50.66, 26),  # 0:50,66  звёздочка конвейера
  @('c01',  52.00, 30),  # 0:52,00  шприцы на лотке
  @('c03', 291.90, 45),  # 4:51,90  руки проверяют перчатку
  @('c08', 361.60, 60),  # 6:01,60  рука на панели станка
  @('c09',  40.48, 58),  # 0:40,48  оператор у термопластавтомата
  @('c10',  44.30, 60),  # 0:44,30  окно в чистое помещение
  @('c11',  89.50, 60),  # 1:29,50  чистое помещение, общий план (и размытый фон под телефоном)
  @('c12',  91.90, 60),  # 1:31,90  чистое помещение, камера идёт в цех
  @('c14', 536.10, 60)   # 8:56,10  роторный узел, уход в расфокус
)

foreach ($c in $clips) {
  $dir = Join-Path $Work ("clips\" + $c[0])
  New-Item -ItemType Directory -Force $dir | Out-Null
  # выпуск закодирован в BT.709; JPEG читается как BT.601, поэтому матрицу пересчитываем явно
  ffmpeg -hide_banner -loglevel error -y -ss $c[1] -i $Source -an -frames:v $c[2] `
    -vf "scale=in_color_matrix=bt709:in_range=tv:out_color_matrix=bt601:out_range=pc" `
    -q:v 2 -pix_fmt yuvj420p (Join-Path $dir "%04d.jpg")
  "{0}: {1} кадров" -f $c[0], (Get-ChildItem $dir).Count
}
